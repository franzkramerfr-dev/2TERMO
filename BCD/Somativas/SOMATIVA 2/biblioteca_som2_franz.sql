-- CRIANDO TABELAS

CREATE TABLE IF NOT EXISTS USUARIO (
    ID_USUARIO INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS EMPRESTIMO (
    ID_EMPRESTIMO INT AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO' CHECK (STATUS_EMPRESTIMO = 'ABERTO'),
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT PK_EMPRESTIMO PRIMARY KEY (ID_EMPRESTIMO),
    CONSTRAINT FK_USUARIO_EMPRESTIMO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_EMPRESTIMO_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO) 
);
    


CREATE TABLE IF NOT EXISTS LIVRO (
    ID_LIVRO INT AUTO_INCREMENT,
    ID_FORNECEDOR INT NOT NULL,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK (QUANTIDADE_DISPONIVEL > 0),
    CONSTRAINT PK_LIVRO PRIMARY KEY (ID_LIVRO),
    CONSTRAINT FK_FORNECEDOR_LIVRO FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR)
);

CREATE TABLE IF NOT EXISTS ESTOQUE (
    ID_ESTOQUE INT AUTO_INCREMENT,
    ID_LIVRO INT NOT NULL,
    NOME_LIVRO VARCHAR(100),
    QUANTIDADE_DISPONIVEL INT,
    NOME_AUTOR VARCHAR (100),
    CONSTRAINT PK_ESTOQUE PRIMARY KEY (ID_ESTOQUE),
    CONSTRAINT FK_ESTOQUE_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO)
);

CREATE TABLE IF NOT EXISTS FORNECEDOR (
    ID_FORNECEDOR INT AUTO_INCREMENT,
    NOME_FORNECEDOR VARCHAR(100),
    TELEFONE_FORNECEDOR VARCHAR(20),
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY (ID_FORNECEDOR)
);

