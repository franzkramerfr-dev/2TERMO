-- 19. GROUP BY — 4 pts
-- Mostre cada usuário e sua quantidade de empréstimos, do maior para o menor.

SELECT U.ID_USUARIO, U.NOME, COUNT(E.ID_EMPRESTIMO) AS QUANTIDADE_EMPRESTIMOS
FROM USUARIO AS U
    INNER JOIN EMPRESTIMO AS E ON U.ID_USUARIO = E.ID_USUARIO
GROUP BY
    U.ID_USUARIO,
    U.NOME
ORDER BY QUANTIDADE_EMPRESTIMOS DESC;

-- 20. LEFT JOIN — 4 pts
-- Liste todos os usuários, inclusive os que nunca fizeram empréstimo, com a
-- quantidade de empréstimos de cada um.

SELECT U.ID_USUARIO, U.NOME, COUNT(E.ID_EMPRESTIMO) AS QUANTIDADE_EMPRESTIMOS
FROM USUARIO AS U
    LEFT JOIN EMPRESTIMO AS E ON U.ID_USUARIO = E.ID_USUARIO
GROUP BY
    U.ID_USUARIO,
    U.NOME
ORDER BY QUANTIDADE_EMPRESTIMOS DESC;

