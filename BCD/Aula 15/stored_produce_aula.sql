-- EX 2: CONSULTA SIMPLES

DELIMITER $$

CREATE PROCEDURE LISTAR_PRODUTOS()
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM produto
    WHERE ATIVO = TRUE
    ORDER BY NOME;
END
DELIMITER ; 

CALL LISTAR_PRODUTOS();

-- OBS: A PROCEDURE NÃO RECEBE PARAMETROS, APENAS EXECUTA UMA CONSULTA PADRONIZADA

-- EX 3: PARAMETROS IN - REPRESENTA UM VALOR ENVIADO PARA A PROCEDURE

DELIMITER $$

CREATE PROCEDURE BUSCAR_PRODUTOS_CATEGORIA (IN P_ID_CATEGORIA INT)
BEGIN
    SELECT ID_PRODUTO AS CÓDIGO, NOME, PRECO
    FROM produto
    WHERE ID_CATEGORIA = P_ID_CATEGORIA
    AND ATIVO = TRUE
    ORDER BY NOME;
END

DELIMITER ;

CALL BUSCAR_PRODUTOS_CATEGORIA(2)

