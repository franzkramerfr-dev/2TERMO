-- EX 6: VARIÁVEIS LOCAIS - DENTRO DO BEGIN .... END PODEMOS DECLARAR VARIÁVEIS

CREATE PROCEDURE CONSULTAR_PRECO (IN P_ID_PRODUTOS INT)
BEGIN 
    DECLARE V_PRECO DECIMAL (10,2);

    SELECT PRECO
    INTO V_PRECO
    FROM PRODUTO
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    SELECT V_PRECO AS PRECO_PRODUTO;
END $$

DELIMITER ;

CALL CONSULTAR_PRECO(10);

-- EX 7 IF ELSEIF ELSSE - PROCEDURE COM DECISÕES

DELIMITER $$

CREATE PROCEDURE CLASSIFICAR_ESTOQUE ( IN P_ID_PRODUTO INT )
BEGIN
    DECLARE V_QUANTIDADE INT;

    SELECT QUANTIDADE
    INTO V_QUANTIDADE
    FROM estoque
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    IF V_QUANTIDADE = 0 THEN
        SELECT 'SEM ESTOQUE' AS SITUAÇÃO;
    ELSEIF V_QUANTIDADE <=5 THEN
        SELECT 'ESTOQUE BAIXO' AS SITUAÇÃO;
    ELSE
        SELECT 'ESTOQUE NORMAL' AS SITUAÇÃO;
    END IF;
END $$

DELIMITER ;

CALL CLASSIFICAR_ESTOQUE(2)

